package com.lbisoft.core.framework.useractivities;

public class ActivityType {

  private String activityLk;
  private String description;
  private String relatedBoolName;
  private String relatedDateName;
  private String relatedIdName;
  private String relatedNumberName;
  private String relatedStringName;
  private String relatedObjectName;
  private String resourceName;

  public String getActivityLk() {
    return activityLk;
  }

  public void setActivityLk(String activityLk) {
    this.activityLk = activityLk;
  }

  public String getDescription() {
    return description;
  }

  public void setDescription(String description) {
    this.description = description;
  }

  public String getRelatedBoolName() {
    return relatedBoolName;
  }

  public void setRelatedBoolName(String relatedBoolName) {
    this.relatedBoolName = relatedBoolName;
  }

  public String getRelatedDateName() {
    return relatedDateName;
  }

  public void setRelatedDateName(String relatedDateName) {
    this.relatedDateName = relatedDateName;
  }

  public String getRelatedIdName() {
    return relatedIdName;
  }

  public void setRelatedIdName(String relatedIdName) {
    this.relatedIdName = relatedIdName;
  }

  public String getRelatedNumberName() {
    return relatedNumberName;
  }

  public void setRelatedNumberName(String relatedNumberName) {
    this.relatedNumberName = relatedNumberName;
  }

  public String getRelatedStringName() {
    return relatedStringName;
  }

  public void setRelatedStringName(String relatedStringName) {
    this.relatedStringName = relatedStringName;
  }

  public String getRelatedObjectName() {
    return relatedObjectName;
  }

  public void setRelatedObjectName(String relatedObjectName) {
    this.relatedObjectName = relatedObjectName;
  }

  public String getResourceName() {
    return resourceName;
  }

  public void setResourceName(String resourceName) {
    this.resourceName = resourceName;
  }


}
